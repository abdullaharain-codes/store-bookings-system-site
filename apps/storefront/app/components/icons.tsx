/**
 * Inline SVG icons for the site shell.
 *
 * The reference prototypes load the Material Symbols webfont, but that adds a
 * render-blocking third-party stylesheet to every page and ships the whole icon
 * set for the six glyphs actually used. These are stroke-based and inherit
 * `currentColor`, so they follow the surrounding token without a second class.
 *
 * All of them are `aria-hidden`: every icon in the shell sits inside a link or
 * button that carries its own accessible name, so exposing the glyph as well
 * would make screen readers announce the path data.
 */

